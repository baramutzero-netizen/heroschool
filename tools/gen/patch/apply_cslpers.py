def sub1(src, old, new):
    n = src.count(old)
    if n != 1:
        raise RuntimeError("자리를 못 찾았다 (%d): %s" % (n, old[:120]))
    return src.replace(old, new)


def apply(src):
    i = src.index("const COUNSEL = [")
    if END_MARK in src: j = src.index(END_MARK) + len(END_MARK)
    else: j = src.index(OLD_END) + len("];\n")
    src = src[:i] + BLOCK + src[j:]
    for old, new in EDITS:
        if new in src: continue
        src = sub1(src, old, new)
    return src


